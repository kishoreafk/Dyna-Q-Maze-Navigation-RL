/**
 * Builds the login document. Unlike the original Neuform "focus" builder, the
 * login integration must keep the WHOLE page visible (card + canvas), so no
 * target isolation is applied — the source is used as-is.
 */
function buildLoginDocument(source: string) {
  return source;
}

export default function GatewayFlow({
  className,
  style,
}: GatewayFlowProps) {
  const iframeRef = useRef<HTMLIFrameElement>(null);

  useEffect(() => {
    // Keep a reference alive for future control-channel extensions.
    void iframeRef.current;
  }, []);

  return (
    <iframe
      ref={iframeRef}
      className={className}
      title="CAVR-Dyna Nexus Gateway"
      srcDoc={buildLoginDocument(gatewayFlowSource)}
      sandbox="allow-scripts allow-same-origin allow-forms"
      loading="eager"
      style={{
        display: "block",
        width: "100%",
        height: "100%",
        border: 0,
        background: "#000000",
        ...style,
      }}
    />
  );
}
